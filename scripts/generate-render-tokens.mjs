/**
 * Writes the static renderers' token block from the app's theme.
 *
 * A card renders inside someone else's document, with none of Atelier's
 * stylesheet loaded, so its palette has to travel with it as literal values.
 * Copying them by hand is how they drift — four of them had, before a review
 * caught it. These are read out of `src/shell/theme.css` instead, resolved
 * through `var()` chains and `color-mix()` over the card's white ground.
 *
 * Run: node scripts/generate-render-tokens.mjs [--check]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const THEME = join(root, "src/shell/theme.css");
const OUT = join(root, "src/render/tokens.generated.ts");

/** The tokens a static render may use, and where each comes from. */
const TOKENS = {
	ink: "--color-text-primary",
	"ink-muted": "--color-text-secondary",
	"ink-subtle": "--color-text-tertiary",
	bg: "--color-bg-panel",
	"bg-muted": "--color-bg-panel-muted",
	border: "--color-border-panel",
	"border-subtle": "--color-border-subtle",
	accent: "--color-icon-brand",
	action: "--color-bg-action-primary",
	"added-bg": "--color-bg-diff-added",
	"added-ink": "--color-text-diff-added",
	"added-edge": "--color-border-diff-added",
	"removed-bg": "--color-bg-diff-removed",
	"removed-ink": "--color-text-diff-removed",
	"removed-edge": "--color-border-diff-removed",
	"modified-bg": "--color-bg-selection-current",
	"moved-edge": "--color-icon-diff-moved",
};

const LITERALS = {
	"font-sans": `ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif`,
	"font-mono": "ui-monospace, SFMono-Regular, Menlo, Consolas, monospace",
	radius: "8px",
	"radius-small": "4px",
};

/** The ground a card composites over; `color-mix(… transparent)` resolves on it. */
const GROUND = [255, 255, 255];

function declarations(css) {
	// Tailwind's @theme blocks are where the app declares its tokens.
	const blocks = [...css.matchAll(/@theme[^{]*\{([\s\S]*?)\n\}/g)];
	if (blocks.length === 0) throw new Error("theme.css has no @theme block");
	const map = new Map();
	for (const block of blocks)
		for (const match of block[1].matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g))
			map.set(match[1], match[2].replace(/\s+/g, " ").trim());
	return map;
}

function resolve(value, map, seen = new Set()) {
	let resolved = value;
	for (let pass = 0; pass < 10 && /var\(/.test(resolved); pass += 1) {
		resolved = resolved.replace(
			/var\((--[\w-]+)(?:,\s*([^)]*))?\)/g,
			(_, name, fallback) => {
				if (seen.has(name)) throw new Error(`token cycle at ${name}`);
				const next = map.get(name);
				if (next === undefined) {
					if (fallback !== undefined) return fallback;
					throw new Error(`theme.css does not define ${name}`);
				}
				return next;
			},
		);
	}
	const mix =
		/^color-mix\(\s*in srgb,\s*(rgb\([^)]*\))\s*([\d.]+)%,\s*transparent\s*\)$/.exec(
			resolved,
		);
	if (mix) return over(mix[1], Number(mix[2]) / 100);
	if (/color-mix|var\(/.test(resolved))
		throw new Error(`unresolved token value: ${resolved}`);
	return resolved;
}

function over(rgb, alpha) {
	const parts = rgb.match(/[\d.]+/g)?.map(Number) ?? [];
	if (parts.length < 3) throw new Error(`not an rgb() value: ${rgb}`);
	const blend = parts
		.slice(0, 3)
		.map((channel, index) =>
			Math.round(channel * alpha + GROUND[index] * (1 - alpha)),
		);
	return `rgb(${blend.join(", ")})`;
}

const map = declarations(readFileSync(THEME, "utf8"));
const lines = [
	...Object.entries(TOKENS).map(
		([name, source]) =>
			`\t--atelier-${name}: ${resolve(
				map.get(source) ??
					(() => {
						throw new Error(`theme.css does not define ${source}`);
					})(),
				map,
			)};`,
	),
	...Object.entries(LITERALS).map(
		([name, value]) => `\t--atelier-${name}: ${value};`,
	),
];

const file = `// Generated by scripts/generate-render-tokens.mjs from src/shell/theme.css.
// Do not edit: run \`pnpm run tokens\` after changing the theme.

/**
 * The palette a static render carries, so it needs no stylesheet of ours.
 *
 * Declared on the document root, not on the render itself: a value declared
 * on the element beats one inherited from an ancestor, so tokens set here
 * would silently overrule the host. Defined at the root, the nearest
 * ancestor that redefines one wins — which is how a host retints.
 */
export const ATELIER_RENDER_TOKENS = \`:root {
${lines.join("\n")}
}\`;
`;

if (process.argv.includes("--check")) {
	const current = readFileSync(OUT, "utf8");
	if (current !== file) {
		console.error(
			"src/render/tokens.generated.ts is stale; run: pnpm run tokens",
		);
		process.exit(1);
	}
	console.log("tokens up to date");
} else {
	writeFileSync(OUT, file);
	console.log(`wrote ${OUT}`);
}
